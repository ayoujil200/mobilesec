"""
Build an ML training CSV from controlled-template ground truth.

Input files:
  1. ground_truth_labels.csv from scripts/generate_controlled_android_dataset.py
  2. batch-upload-results-*.json from scripts/upload-apk-folder.js

The script extracts numeric scanner features from MongoDB by scan_id, then
overwrites fix_category with the controlled-template ground truth. This avoids
training on labels generated by scanners.

Example inside the ml-model container:
  python -m src.data.build_controlled_dataset \
    --labels backend/ml-model/experiments/controlled_android_dataset/ground_truth_labels.csv \
    --uploads batch-upload-results-2026-05-16T10-00-00-000Z.json \
    --output data/security_scan_dataset.csv
"""

from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path
from typing import Dict, List, Optional

import pandas as pd

from .data_extractor import DataExtractor


logger = logging.getLogger(__name__)


def _normalize_path(value: str) -> str:
    return str(value).replace("\\", "/").lower()


def _load_upload_scan_map(upload_paths: List[Path]) -> Dict[str, str]:
    """Return path/basename keys mapped to scan_id from upload result JSON files."""
    scan_map: Dict[str, str] = {}

    for upload_path in upload_paths:
        with upload_path.open("r", encoding="utf-8") as handle:
            payload = json.load(handle)

        for result in payload.get("results", []):
            scan_id = result.get("scanId") or result.get("scan_id") or result.get("body", {}).get("scan_id")
            file_path = result.get("file")
            if not scan_id or not file_path:
                continue

            normalized = _normalize_path(file_path)
            scan_map[normalized] = scan_id
            scan_map[Path(normalized).name] = scan_id

    return scan_map


def _find_scan_id(label_row: pd.Series, scan_map: Dict[str, str]) -> Optional[str]:
    if pd.notnull(label_row.get("scan_id")) and str(label_row.get("scan_id")).strip():
        return str(label_row.get("scan_id")).strip()

    candidates = []
    for column in ["apk_path", "project_name"]:
        value = label_row.get(column)
        if pd.notnull(value) and str(value).strip():
            normalized = _normalize_path(str(value))
            candidates.append(normalized)
            candidates.append(Path(normalized).name)
            if column == "project_name":
                candidates.append(f"{normalized}.apk")

    for candidate in candidates:
        if candidate in scan_map:
            return scan_map[candidate]

    return None


def build_dataset(labels_path: Path, upload_paths: List[Path], output_path: Path) -> pd.DataFrame:
    labels_df = pd.read_csv(labels_path)
    required = {"fix_category", "label_source", "label_confidence", "label_review_status"}
    missing = required - set(labels_df.columns)
    if missing:
        raise ValueError(f"Ground-truth labels CSV is missing columns: {sorted(missing)}")

    scan_map = _load_upload_scan_map(upload_paths)
    if not scan_map:
        raise ValueError("No scan IDs found in upload result files.")

    extractor = DataExtractor()
    if not extractor.connect():
        raise ConnectionError("Failed to connect to MongoDB.")

    records = []
    skipped = []
    try:
        for _, label_row in labels_df.iterrows():
            scan_id = _find_scan_id(label_row, scan_map)
            if not scan_id:
                skipped.append({
                    "project_name": label_row.get("project_name"),
                    "apk_path": label_row.get("apk_path"),
                    "reason": "scan_id_not_found",
                })
                continue

            features = extractor._extract_scan_features(scan_id)
            if not features:
                skipped.append({
                    "project_name": label_row.get("project_name"),
                    "apk_path": label_row.get("apk_path"),
                    "scan_id": scan_id,
                    "reason": "features_not_found",
                })
                continue

            features["scan_id"] = scan_id
            features["sample_id"] = label_row.get("sample_id")
            features["project_name"] = label_row.get("project_name")
            features["apk_path"] = label_row.get("apk_path")
            features["fix_category"] = str(label_row["fix_category"])
            features["label_source"] = str(label_row["label_source"])
            features["label_confidence"] = float(label_row["label_confidence"])
            features["label_review_status"] = str(label_row["label_review_status"])
            features["label_evidence"] = json.dumps([{
                "source": label_row.get("label_source"),
                "template_id": label_row.get("template_id"),
                "ground_truth_rule": label_row.get("ground_truth_rule"),
            }], ensure_ascii=True)
            features["candidate_fix_categories"] = json.dumps({
                features["fix_category"]: {"count": 1, "score": 100}
            }, ensure_ascii=True)

            records.append(features)
    finally:
        extractor.disconnect()

    if not records:
        raise ValueError(f"No feature rows were created. Skipped rows: {skipped[:5]}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(records)
    df.to_csv(output_path, index=False)

    skipped_path = output_path.with_suffix(".skipped.json")
    with skipped_path.open("w", encoding="utf-8") as handle:
        json.dump(skipped, handle, indent=2, ensure_ascii=True)

    logger.info("Wrote %s trusted training rows to %s", len(df), output_path)
    logger.info("Skipped %s rows. Details: %s", len(skipped), skipped_path)
    return df


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build trusted controlled-template ML dataset from scan results.")
    parser.add_argument("--labels", required=True, type=Path, help="Path to ground_truth_labels.csv.")
    parser.add_argument(
        "--uploads",
        required=True,
        nargs="+",
        type=Path,
        help="One or more batch-upload-results JSON files.",
    )
    parser.add_argument("--output", default=Path("data/security_scan_dataset.csv"), type=Path)
    return parser.parse_args()


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    args = parse_args()
    df = build_dataset(args.labels, args.uploads, args.output)
    print(f"Rows: {len(df)}")
    print(f"Output: {args.output}")
    print("Class distribution:")
    print(df["fix_category"].value_counts().sort_index().to_string())


if __name__ == "__main__":
    main()
